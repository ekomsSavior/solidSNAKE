func protocolCheck(path string) {
	raw, err := os.ReadFile(path)
	if err != nil {
		fail("read %s: %v", path, err)
	}
	var b struct {
		Beacon     rrprotocol.BeaconPayload `json:"beacon"`
		Task       rrprotocol.Task          `json:"task"`
		TaskResult rrprotocol.TaskResult    `json:"task_result"`
	}
	if err := json.Unmarshal(raw, &b); err != nil {
		fail("unmarshal C++ artifacts: %v", err)
	}

	if b.Beacon.ID != "imp-cpp-7" || b.Beacon.Type != rrprotocol.ImplantWindows ||
		b.Beacon.Target != "cpp-target" {
		fail("beacon id/type/target mismatch: %+v", b.Beacon)
	}
	if b.Beacon.Timestamp != 1758302500 || b.Beacon.Jitter != 0.5 {
		fail("beacon ts/jitter mismatch: %+v", b.Beacon)
	}
	if b.Beacon.Hostname != "cpp-host" || b.Beacon.Arch != "amd64" || b.Beacon.PeerAddr != "10.0.0.7" {
		fail("beacon hostname/arch/peer_addr mismatch: %+v", b.Beacon)
	}
	fmt.Println("OK: Go parsed C++ beacon (all fields exact, incl. omitempty-populated)")

	if b.Task.ID != "t-2002" || b.Task.Type != "shell" || b.Task.TTL != 30 {
		fail("task id/type/ttl mismatch: %+v", b.Task)
	}
	if len(b.Task.Payload) != 2 || b.Task.Payload["cmd"] != "whoami" || b.Task.Payload["arg"] != "-a" {
		fail("task payload mismatch: %+v", b.Task.Payload)
	}
	fmt.Println("OK: Go parsed C++ task (payload map exact)")

	if b.TaskResult.TaskID != "t-2002" || !b.TaskResult.Success ||
		b.TaskResult.Output != "uid=0(root)" || b.TaskResult.Error != "" {
		fail("task_result mismatch: %+v", b.TaskResult)
	}
	fmt.Println("OK: Go parsed C++ task_result (success/output exact, error omitted)")
}

// dnsCheck verifies C++-produced DNS exfil queries through the real tunnel parser:
// ParseFragment -> ReceiveFragment -> Reconstruct -> AEAD decrypt.
func dnsCheck(path string) {
	raw, err := os.ReadFile(path)
	if err != nil {
		fail("read %s: %v", path, err)
	}
	var sessionKeyHex, domain, payloadHex string
	var queries []string
	for _, line := range strings.Split(string(raw), "\n") {
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		if p := strings.Index(line, "="); p >= 0 {
			switch line[:p] {
			case "session_key_hex":
				sessionKeyHex = line[p+1:]
			case "domain":
				domain = line[p+1:]
			case "payload_hex":
				payloadHex = line[p+1:]
			default:
				fail("unknown header field: %s", line[:p])
			}
			continue
		}
		queries = append(queries, line)
	}
	if sessionKeyHex == "" || domain == "" || payloadHex == "" || len(queries) == 0 {
		fail("missing header fields or queries")
	}
	sk, err := hex.DecodeString(sessionKeyHex)
	if err != nil || len(sk) != 32 {
		fail("bad session_key_hex")
	}
	wantPayload, err := hex.DecodeString(payloadHex)
	if err != nil {
		fail("bad payload_hex")
	}

	key := rrcrypto.DeriveSessionKey(sk, []byte("dns-tunnel"))
	t := rrdns.New(domain, key)

	session := ""
	complete := false
	for _, q := range queries {
		f := t.ParseFragment(q)
		if f == nil {
			fail("ParseFragment rejected: %s", q)
		}
		if session == "" {
			session = f.SessionID
		} else if f.SessionID != session {
			fail("session id changed mid-transfer")
		}
		if t.ReceiveFragment(f) {
			complete = true
		}
	}
	if !complete {
		fail("transfer never marked complete (last-chunk heuristic)")
	}
	got, err := t.Reconstruct(session)
	if err != nil {
		fail("reconstruct: %v", err)
	}
	if !bytes.Equal(got, wantPayload) {
		fail("payload mismatch after reassembly: %q", got)
	}
	fmt.Println("OK: Go tunnel parser reassembled C++ DNS exfil payload (ParseFragment/ReceiveFragment/Reconstruct/decrypt)")
}

func main() {
	if len(os.Args) < 2 {
		fmt.Fprintln(os.Stderr, "usage: vecgen gen|protocol-gen | vecgen check|protocol-check <file>")
		os.Exit(2)
	}
	switch os.Args[1] {
	case "gen":
		gen()
	case "check":
		if len(os.Args) < 3 {
			fmt.Fprintln(os.Stderr, "usage: vecgen check <artifacts.txt>")
			os.Exit(2)
		}
		check(os.Args[2])
	case "protocol-gen":
		protocolGen()
	case "protocol-check":
		if len(os.Args) < 3 {
			fmt.Fprintln(os.Stderr, "usage: vecgen protocol-check <artifacts.json>")
			os.Exit(2)
		}
		protocolCheck(os.Args[2])
	case "dns-check":
		if len(os.Args) < 3 {
			fmt.Fprintln(os.Stderr, "usage: vecgen dns-check <queries.txt>")
			os.Exit(2)
		}
		dnsCheck(os.Args[2])
	default:
		fmt.Fprintln(os.Stderr, "unknown mode:", os.Args[1])
		os.Exit(2)
	}
}
