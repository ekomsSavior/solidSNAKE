// vecgen — Go-side interop fixture generator / verifier (canonical copy; staged into the
// RANGER_C3 module by scripts/interop.sh, e.g. /tmp/interop-mod/cmd/vecgen/main.go).
//
// Modes:
//
//	gen             — crypto fixtures for the C++ test suite
//	check <file>    — verify C++ crypto artifacts via production Go code paths
//	protocol-gen    — protocol JSON fixtures (marshaled by the Go structs)
//	protocol-check <file> — verify C++ protocol artifacts via Go unmarshal
package main

import (
	"bytes"
	"crypto/ed25519"
	"crypto/sha256"
	"encoding/base64"
	"encoding/hex"
	"encoding/json"
	"fmt"
	"os"
	"strings"

	"golang.org/x/crypto/chacha20poly1305"

	rrcrypto "git.churchofmalware.org/ek0mssavi0r/Ranger-C3/internal/crypto"
	rrdns "git.churchofmalware.org/ek0mssavi0r/Ranger-C3/internal/dns"
	rrprotocol "git.churchofmalware.org/ek0mssavi0r/Ranger-C3/internal/protocol"
)

func fail(format string, args ...any) {
	fmt.Fprintf(os.Stderr, "FAIL: "+format+"\n", args...)
	os.Exit(1)
}

// ---------------------------------------------------------------- crypto ----

func gen() {
	var b strings.Builder

	key := make([]byte, 32)
	for i := range key {
		key[i] = byte(i)
	}
	nonce := make([]byte, 24)
	for i := range nonce {
		nonce[i] = byte(i)
	}
	pt := []byte("ranger c3 interop vector")
	aead, err := chacha20poly1305.NewX(key)
	if err != nil {
		fail("NewX: %v", err)
	}
	blob := aead.Seal(append([]byte{}, nonce...), nonce, pt, nil)
	if out, err := rrcrypto.DecryptWithAEAD(key, blob); err != nil || string(out) != string(pt) {
		fail("production DecryptWithAEAD rejected our own blob")
	}

	seed := make([]byte, 32)
	for i := range seed {
		seed[i] = byte(i + 1)
	}
	priv := ed25519.NewKeyFromSeed(seed)
	pub := priv.Public().(ed25519.PublicKey)
	data := []byte("mesh heartbeat interop")
	ts := int64(1758302400)
	nonceB := make([]byte, 16)
	for i := range nonceB {
		nonceB[i] = byte(0xa0 + i)
	}
	nonceStr := base64.RawStdEncoding.EncodeToString(nonceB)
	msg := append(append([]byte{}, data...), []byte(fmt.Sprintf("%d%s", ts, nonceStr))...)
	sig := ed25519.Sign(priv, msg)

	dsKey := rrcrypto.DeriveSessionKey([]byte("shared-secret"), []byte("dns-tunnel"))
	sh := sha256.Sum256([]byte("solidsnake-native"))

	pemBytes, err := rrcrypto.MarshalPublicKey(pub)
	if err != nil {
		fail("MarshalPublicKey: %v", err)
	}

	fmt.Fprintf(&b, "# Ranger C3 interop fixtures — generated by interop/vecgen.go (do not edit)\n")
	fmt.Fprintf(&b, "aead_key_hex=%s\n", hex.EncodeToString(key))
	fmt.Fprintf(&b, "aead_nonce_hex=%s\n", hex.EncodeToString(nonce))
	fmt.Fprintf(&b, "aead_pt_hex=%s\n", hex.EncodeToString(pt))
	fmt.Fprintf(&b, "aead_blob_hex=%s\n", hex.EncodeToString(blob))
	fmt.Fprintf(&b, "sign_seed_hex=%s\n", hex.EncodeToString(seed))
	fmt.Fprintf(&b, "sign_pub_hex=%s\n", hex.EncodeToString(pub))
	fmt.Fprintf(&b, "sign_data_hex=%s\n", hex.EncodeToString(data))
	fmt.Fprintf(&b, "sign_ts=%d\n", ts)
	fmt.Fprintf(&b, "sign_nonce_b64=%s\n", nonceStr)
	fmt.Fprintf(&b, "sign_sig_hex=%s\n", hex.EncodeToString(sig))
	fmt.Fprintf(&b, "ds_secret_hex=%s\n", hex.EncodeToString([]byte("shared-secret")))
	fmt.Fprintf(&b, "ds_salt_hex=%s\n", hex.EncodeToString([]byte("dns-tunnel")))
	fmt.Fprintf(&b, "ds_key_hex=%s\n", hex.EncodeToString(dsKey))
	fmt.Fprintf(&b, "sha_in_hex=%s\n", hex.EncodeToString([]byte("solidsnake-native")))
	fmt.Fprintf(&b, "sha_out_hex=%s\n", hex.EncodeToString(sh[:]))
	fmt.Fprintf(&b, "pem_b64=%s\n", base64.StdEncoding.EncodeToString(pemBytes))
	fmt.Print(b.String())
}

func check(path string) {
	raw, err := os.ReadFile(path)
	if err != nil {
		fail("read %s: %v", path, err)
	}
	kv := map[string]string{}
	for _, line := range strings.Split(string(raw), "\n") {
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		if p := strings.Index(line, "="); p >= 0 {
			kv[line[:p]] = line[p+1:]
		}
	}
	getHex := func(k string) []byte {
		v, err := hex.DecodeString(kv[k])
		if err != nil {
			fail("field %s: %v", k, err)
		}
		return v
	}

	pt, err := rrcrypto.DecryptWithAEAD(getHex("cpp_aead_key_hex"), getHex("cpp_aead_blob_hex"))
	if err != nil {
		fail("Go DecryptWithAEAD on C++ blob: %v", err)
	}
	if hex.EncodeToString(pt) != kv["cpp_aead_pt_hex"] {
		fail("C++ AEAD plaintext mismatch after Go decrypt")
	}
	fmt.Println("OK: Go decrypted C++ AEAD blob (production DecryptWithAEAD)")

	pub := ed25519.PublicKey(getHex("cpp_sign_pub_hex"))
	data := getHex("cpp_sign_data_hex")
	sig := getHex("cpp_sign_sig_hex")
	var ts int64
	if _, err := fmt.Sscanf(kv["cpp_sign_ts"], "%d", &ts); err != nil {
		fail("cpp_sign_ts parse: %v", err)
	}
	if err := rrcrypto.Verify(pub, data, sig, kv["cpp_sign_nonce_b64"], ts, map[string]bool{}); err != nil {
		fail("Go Verify on C++ signature: %v", err)
	}
	fmt.Println("OK: Go verified C++ Ed25519 signature (production Verify)")
}

